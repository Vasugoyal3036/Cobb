/**
 * Cobb Multi-Store Interactive Setup Utility
 * Run via: node setup_store.js
 */
const fs = require('fs');
const path = require('path');
const readline = require('readline');

const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
});

const ask = (query, defaultVal) => new Promise((resolve) => {
    rl.question(`${query} [${defaultVal}]: `, (answer) => {
        resolve(answer.trim() || defaultVal);
    });
});

async function run() {
    console.log('\n======================================================');
    console.log('       COBB STORE ONBOARDING & SETUP WIZARD');
    console.log('======================================================\n');
    console.log('This wizard configures this computer as an active Cobb store node.\n');

    const storeCity = await ask('Store Location / City', 'Nigdhu');
    const defaultCode = storeCity.toUpperCase().replace(/[^A-Z]/g, '').slice(0, 8);
    const storeCode = await ask('Short Store Code', defaultCode);
    const storeName = await ask('Full Store Display Name', `Cobb ${storeCity}`);
    const storeId = await ask('Unique Store Firebase ID', `STORE_${defaultCode}_002`);
    const storeLocation = await ask('Store Address', `Main Market, ${storeCity}`);

    console.log('\n--- POS Database Settings ---');
    const dbServer = await ask('SQL Server Instance', 'localhost\\SQLEXPRESS');
    const dbName = await ask('POS Database Name', 'RPD_AVATAR01_NEW_ST_POS');

    const envContent = `# Auto-generated by setup_store.js on ${new Date().toISOString()}
STORE_ID=${storeId}
STORE_NAME=${storeName}
STORE_LOCATION=${storeLocation}
STORE_CODE=${storeCode}

DB_SERVER=${dbServer}
DB_NAME=${dbName}
DB_USER=
DB_PASSWORD=

PORT=5000
WHATSAPP_GATEWAY_PORT=3000
OWNER_WHATSAPP_NUMBERS=9138122820,8708788707,9034522000,9466422821
WHATSAPP_GATEWAY_URL=http://localhost:3000/send

GEMINI_API_KEY=\${process.env.GEMINI_API_KEY || 'your_gemini_api_key_here'}
GEMINI_MODEL=gemini-3.6-flash
`;

    const envPath = path.join(__dirname, '.env');
    fs.writeFileSync(envPath, envContent, 'utf8');

    console.log('\n✅ Configuration saved to CobbDashboard/.env');
    console.log(`\nStore Details:`);
    console.log(`- ID: ${storeId}`);
    console.log(`- Name: ${storeName}`);
    console.log(`- City: ${storeCity}`);
    console.log(`- DB: ${dbServer} -> ${dbName}`);
    console.log('\nReady! You can now start the background services using:');
    console.log('  pm2 start server.js --name cobb-backend\n');

    rl.close();
}

run().catch((err) => {
    console.error('Setup error:', err);
    rl.close();
});
