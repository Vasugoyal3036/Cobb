/**
 * dynamicBreakevenEngine.js
 * 
 * Retail Rolling Deficit & Dynamic Breakeven Calculator for Cobb Pundri.
 * 
 * Rule requested by store owner:
 * "calculates the loss and profit for every day and adjust the breakeven according to that.
 * like if breakeven is at 13467 and on that particular day the store made a loss of 1000 rs,
 * then on the next day it should show the loss of the previous days combined up and create a new breakeven for every single day."
 */

export function calculateDynamicBreakeven({
  dailySales = [],
  expenses = [],
  storeConfig = null,
  pnlData = null,
  overviewStats = null,
  targetMonth = null // YYYY-MM (defaults to current month)
}) {
  // 1. Establish Store Financial Constants
  const expCfg = storeConfig?.operatingExpenses || pnlData?.operatingExpenses || {};
  
  const rent = Number(expCfg.rent !== undefined ? expCfg.rent : 40000);
  const electricity = Number(expCfg.electricity !== undefined ? expCfg.electricity : 15000);
  const staffSalaries = Number(expCfg.staffSalaries !== undefined ? expCfg.staffSalaries : 45000);
  const miscExpenses = Number(expCfg.miscExpenses !== undefined ? expCfg.miscExpenses : 10000);
  const franchiseRoyalty = Number(expCfg.franchiseRoyalty !== undefined ? expCfg.franchiseRoyalty : 0);
  const totalMonthlyExpenses = rent + electricity + staffSalaries + miscExpenses + franchiseRoyalty;
  
  const targetMarginPct = Number(expCfg.targetMarginPct !== undefined ? expCfg.targetMarginPct : 27);
  const marginFrac = targetMarginPct / 100;
  
  const baseDailyOpEx = Number(
    expCfg.dailyExpense || 
    expCfg.dailyOpEx || 
    expCfg.dailyAmortizedExpense || 
    Math.round(totalMonthlyExpenses / 30) ||
    3367
  );

  // Base Daily Break-even (e.g. ₹13,467 or ₹13,468)
  const baseDailyBEP = marginFrac > 0 
    ? Math.round(baseDailyOpEx / marginFrac) 
    : Math.round(baseDailyOpEx / 0.27);

  // 2. Determine Tracking Month
  const now = new Date();
  const currentMonthKey = targetMonth || now.toISOString().slice(0, 7); // 'YYYY-MM'
  const todayDateStr = now.toISOString().split('T')[0];

  // 3. Filter and Sort Daily Sales for target month
  const salesArray = Array.isArray(dailySales) ? dailySales : [];
  const monthSales = salesArray
    .filter(d => {
      const rawDate = String(d.SaleDate || d.date || '');
      return rawDate.startsWith(currentMonthKey);
    })
    .map(d => {
      const rawDate = String(d.SaleDate || d.date || '').slice(0, 10);
      return {
        date: rawDate,
        sales: Number(d.TotalSales || d.sales || 0),
        bills: Number(d.BillCount || d.bills || 0),
        cash: Number(d.CashAmount || 0),
        upi: Number(d.UPIAmount || 0),
        card: Number(d.CardAmount || 0)
      };
    })
    .sort((a, b) => a.date.localeCompare(b.date));

  // If today is in the current month but not yet recorded in SQL dailySales, inject today from overviewStats
  const todayInMonth = monthSales.find(d => d.date === todayDateStr);
  const todayLiveSales = Number(overviewStats?.today?.TotalSales || 0);
  const todayLiveBills = Number(overviewStats?.today?.BillCount || 0);

  if (!todayInMonth && todayLiveSales > 0 && todayDateStr.startsWith(currentMonthKey)) {
    monthSales.push({
      date: todayDateStr,
      sales: todayLiveSales,
      bills: todayLiveBills,
      cash: Number(overviewStats?.today?.CashAmount || 0),
      upi: Number(overviewStats?.today?.UPIAmount || 0),
      card: Number(overviewStats?.today?.CardAmount || 0)
    });
    monthSales.sort((a, b) => a.date.localeCompare(b.date));
  } else if (todayInMonth && todayLiveSales > todayInMonth.sales) {
    // Update with live higher sales if bills were entered today
    todayInMonth.sales = todayLiveSales;
    todayInMonth.bills = Math.max(todayInMonth.bills, todayLiveBills);
  }

  // 4. Group Expenses by Date
  const expensesArray = Array.isArray(expenses) ? expenses : [];
  const expensesByDate = {};
  expensesArray.forEach(e => {
    const dStr = String(e.date || '').slice(0, 10);
    if (dStr) {
      expensesByDate[dStr] = (expensesByDate[dStr] || 0) + (Number(e.amount) || 0);
    }
  });

  // 5. Day-by-Day Compounding Loss & Dynamic Breakeven Loop (2-Way Profit & Loss Rolling Balance)
  let cumulativeLossOnly = 0;
  let rollingNetBalance = 0; // Signed balance: + for surplus profit cushion, - for deficit
  let totalProfitsRecovered = 0;
  let totalDeficitIncurred = 0;
  const history = [];

  monthSales.forEach((dayRecord) => {
    const date = dayRecord.date;
    const sales = dayRecord.sales;
    const bills = dayRecord.bills;

    // Daily petty cash expenses (or 0)
    const pettyCash = Number(expensesByDate[date] || 0);
    const dayTotalCost = baseDailyOpEx + pettyCash;

    // Gross profit generated by sales
    const grossProfit = Math.round(sales * marginFrac);

    // Net P&L for this day:
    const netDailyProfit = grossProfit - dayTotalCost;
    const isLoss = netDailyProfit < 0;
    const isProfit = netDailyProfit > 0;
    const lossAmount = isLoss ? Math.abs(netDailyProfit) : 0;
    const profitAmount = isProfit ? netDailyProfit : 0;

    if (isLoss) totalDeficitIncurred += lossAmount;
    if (isProfit) totalProfitsRecovered += profitAmount;

    // Balances before today's performance:
    const carriedBalanceBefore = rollingNetBalance; // Signed (+ surplus or - deficit)
    const carriedLossBefore = cumulativeLossOnly;   // Loss-only (>= 0)

    // --- 2-WAY DYNAMIC BREAKEVEN CALCULATION ---
    // If in deficit (< 0): target OpEx increases by deficit to recoup previous losses
    // If in surplus (> 0): previous profits pre-fund today's OpEx, lowering target BEP!
    let dayTargetOpEx = baseDailyOpEx;
    if (carriedBalanceBefore < 0) {
      // Deficit: must cover base OpEx + unrecovered loss
      dayTargetOpEx = baseDailyOpEx + Math.abs(carriedBalanceBefore);
    } else if (carriedBalanceBefore > 0) {
      // Surplus Profit: cushions today's costs
      dayTargetOpEx = Math.max(0, baseDailyOpEx - carriedBalanceBefore);
    }

    // 2-Way Adjusted BEP (Profits reduce BEP, Losses increase BEP)
    const adjustedBEPTwoWay = marginFrac > 0 ? Math.round(dayTargetOpEx / marginFrac) : 0;

    // Loss-Only Adjusted BEP (Losses increase BEP, profits stop at base)
    const adjustedBEPLossOnly = Math.round((baseDailyOpEx + carriedLossBefore) / marginFrac);

    // Active adjusted BEP (Defaults to the complete 2-way figure)
    const adjustedBEP = adjustedBEPTwoWay;

    // After today's performance, update balances:
    rollingNetBalance += netDailyProfit;
    cumulativeLossOnly = Math.max(0, cumulativeLossOnly - netDailyProfit);

    // Next day's projected target:
    let nextDayTargetOpEx = baseDailyOpEx;
    if (rollingNetBalance < 0) {
      nextDayTargetOpEx = baseDailyOpEx + Math.abs(rollingNetBalance);
    } else if (rollingNetBalance > 0) {
      nextDayTargetOpEx = Math.max(0, baseDailyOpEx - rollingNetBalance);
    }
    const nextDayBEPTwoWay = marginFrac > 0 ? Math.round(nextDayTargetOpEx / marginFrac) : 0;
    const nextDayBEPLossOnly = Math.round((baseDailyOpEx + cumulativeLossOnly) / marginFrac);

    history.push({
      date,
      dayName: new Date(date).toLocaleDateString('en-US', { weekday: 'short' }),
      sales,
      bills,
      grossProfit,
      dailyOpEx: baseDailyOpEx,
      pettyExpenses: pettyCash,
      totalCost: dayTotalCost,
      netDailyProfit,
      status: isProfit ? 'PROFIT' : (isLoss ? 'LOSS' : 'BREAKEVEN'),
      isLoss,
      isProfit,
      lossAmount,
      profitAmount,
      // 2-way signed balance fields:
      carriedBalanceBefore,
      isSurplusBefore: carriedBalanceBefore > 0,
      isDeficitBefore: carriedBalanceBefore < 0,
      surplusProfitBefore: Math.max(0, carriedBalanceBefore),
      carriedDeficitBefore: carriedBalanceBefore < 0 ? Math.abs(carriedBalanceBefore) : 0,
      adjustedBEPTwoWay,
      adjustedBEPLossOnly,
      adjustedBEP,
      carriedBalanceAfter: rollingNetBalance,
      isSurplusAfter: rollingNetBalance > 0,
      isDeficitAfter: rollingNetBalance < 0,
      nextDayBEPTwoWay,
      nextDayBEPLossOnly,
      nextDayBEP: nextDayBEPTwoWay,
      // Backwards-compatible aliases:
      carriedLossBefore,
      carriedLossAfter: cumulativeLossOnly,
      isMet: sales >= adjustedBEP,
      gap: Math.max(0, adjustedBEP - sales)
    });
  });

  // 6. Current Day (Today) Dynamic Breakeven Status
  const todayHistoryRecord = history.find(h => h.date === todayDateStr);
  
  const carriedBalanceIntoToday = todayHistoryRecord 
    ? todayHistoryRecord.carriedBalanceBefore 
    : rollingNetBalance;

  const carriedLossIntoToday = todayHistoryRecord 
    ? todayHistoryRecord.carriedLossBefore 
    : cumulativeLossOnly;

  let todayEffectiveCost = baseDailyOpEx;
  if (carriedBalanceIntoToday < 0) {
    todayEffectiveCost = baseDailyOpEx + Math.abs(carriedBalanceIntoToday);
  } else if (carriedBalanceIntoToday > 0) {
    todayEffectiveCost = Math.max(0, baseDailyOpEx - carriedBalanceIntoToday);
  }

  const adjustedBEPToday = marginFrac > 0 ? Math.round(todayEffectiveCost / marginFrac) : 0;
  const currentSalesToday = todayHistoryRecord ? todayHistoryRecord.sales : todayLiveSales;
  const remainingToBreakevenToday = Math.max(0, adjustedBEPToday - currentSalesToday);
  const isTodayBreakevenMet = currentSalesToday >= adjustedBEPToday;
  const todayProgressPct = adjustedBEPToday > 0 
    ? Math.min(100, Math.round((currentSalesToday / adjustedBEPToday) * 100)) 
    : 100;

  // Impact amounts:
  const isSurplusToday = carriedBalanceIntoToday > 0;
  const isDeficitToday = carriedBalanceIntoToday < 0;
  const surplusProfitAmount = Math.max(0, carriedBalanceIntoToday);
  const carriedDeficitAmount = carriedBalanceIntoToday < 0 ? Math.abs(carriedBalanceIntoToday) : 0;
  const salesAdjustmentAmount = Math.round(Math.abs(carriedBalanceIntoToday) / marginFrac);

  return {
    monthKey: currentMonthKey,
    baseDailyOpEx,
    targetMarginPct,
    baseDailyBEP,
    today: {
      date: todayDateStr,
      sales: currentSalesToday,
      baseBEP: baseDailyBEP,
      // 2-way balance metrics:
      carriedBalance: carriedBalanceIntoToday,
      isSurplus: isSurplusToday,
      isDeficit: isDeficitToday,
      surplusProfit: surplusProfitAmount,
      carriedDeficit: carriedDeficitAmount,
      salesAdjustmentAmount,
      // Aliases:
      carriedLossFromPreviousDays: carriedDeficitAmount,
      salesNeededForCarriedLoss: isDeficitToday ? salesAdjustmentAmount : 0,
      salesDiscountFromSurplus: isSurplusToday ? salesAdjustmentAmount : 0,
      adjustedBEPToday,
      adjustedBEPTwoWayToday: adjustedBEPToday,
      adjustedBEPLossOnlyToday: Math.round((baseDailyOpEx + carriedLossIntoToday) / marginFrac),
      remainingToBreakevenToday,
      isTodayBreakevenMet,
      todayProgressPct,
      netDailyProfitToday: todayHistoryRecord ? todayHistoryRecord.netDailyProfit : (Math.round(currentSalesToday * marginFrac) - baseDailyOpEx),
      status: todayHistoryRecord ? todayHistoryRecord.status : (currentSalesToday >= adjustedBEPToday ? 'PROFIT' : 'LOSS')
    },
    monthSummary: {
      rollingNetBalance,
      netMonthPnl: rollingNetBalance,
      isMonthProfitable: rollingNetBalance >= 0,
      totalDeficitIncurred,
      totalProfitsRecovered,
      currentUnrecoveredDeficit: cumulativeLossOnly,
      daysTracked: history.length,
      lossDaysCount: history.filter(h => h.isLoss).length,
      profitDaysCount: history.filter(h => h.status === 'PROFIT').length
    },
    history
  };
}
